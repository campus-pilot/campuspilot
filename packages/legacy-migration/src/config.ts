export function assertTargetWritersDisabled() {
  if (required('MIGRATION_TARGET_WRITERS_DISABLED') !== 'true')
    throw new Error('MIGRATION_TARGET_WRITERS_DISABLED must be true');
}

export function kubernetesWriterFenceConfig() {
  const deployments = required('MIGRATION_WRITER_FENCE_DEPLOYMENTS').split(',').map((item) => item.trim()).filter(Boolean);
  if (!deployments.length || new Set(deployments).size !== deployments.length)
    throw new Error('MIGRATION_WRITER_FENCE_DEPLOYMENTS must name a non-empty unique deployment set');
  if (JSON.stringify(deployments.toSorted()) !== JSON.stringify([...REQUIRED_WRITER_DEPLOYMENTS].toSorted()))
    throw new Error(`MIGRATION_WRITER_FENCE_DEPLOYMENTS must exactly equal the release-pinned writer set: ${REQUIRED_WRITER_DEPLOYMENTS.join(',')}`);
  const namespace = required('MIGRATION_WRITER_FENCE_NAMESPACE');
  if (namespace !== REQUIRED_WRITER_NAMESPACE)
    throw new Error(`MIGRATION_WRITER_FENCE_NAMESPACE must be ${REQUIRED_WRITER_NAMESPACE}`);
  return {
    kubeconfig: requiredFile('MIGRATION_KUBECONFIG_FILE'),
    namespace,
    deployments,
  };
}

