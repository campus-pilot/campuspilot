import path from 'node:path';
import { REQUIRED_WRITER_DEPLOYMENTS, REQUIRED_WRITER_NAMESPACE } from './writer-fence.ts';

export type S3ConnectionConfig = {
  bucket: string;
  region: string;
  endpoint?: string;
  forcePathStyle: boolean;
  accessKeyId: string;
  secretAccessKey: string;
};

function required(name: string) {
  const value = process.env[name]?.trim();
  if (!value) throw new Error(`${name} is required`);
  return value;
}

function optional(name: string) {
  const value = process.env[name]?.trim();
  return value || undefined;
}

function boolean(name: string, fallback: boolean) {
  const value = optional(name);
  if (value === undefined) return fallback;
  if (value === 'true') return true;
  if (value === 'false') return false;
  throw new Error(`${name} must be true or false`);
}

/**
 * Resolve an operator-supplied artifact path. Approval inputs are intentionally
 * explicit and are never discovered or generated by the importer.
 */
export function requiredFile(name: string) {
  return path.resolve(required(name));
}

