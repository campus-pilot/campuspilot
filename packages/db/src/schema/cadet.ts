export const cadetUserRelations = relations(cadetUser, ({ many, one }) => ({
  sessions: many(cadetSession),
  accounts: many(cadetAccount),
  admission: one(admissionTable, {
    fields: [cadetUser.admissionId],
    references: [admissionTable.id],
  }),
}));

export const cadetSessionRelations = relations(cadetSession, ({ one }) => ({
  user: one(cadetUser, {
    fields: [cadetSession.userId],
    references: [cadetUser.id],
  }),
}));

export const cadetAccountRelations = relations(cadetAccount, ({ one }) => ({
  user: one(cadetUser, {
    fields: [cadetAccount.userId],
    references: [cadetUser.id],
  }),
}));
