/**
 * Tables of the Cadet Portal's own Better Auth instance (see
 * `packages/auth/src/cadet.ts`). They mirror the staff auth tables column for
 * column, because the same Better Auth models are mapped onto them through the
 * cadet instance's Drizzle adapter schema map. They live in `public` next to
 * the staff tables; isolation comes from the separate auth instance, so no
 * row, index or constraint here is shared with or referenced by staff auth.
 *
 * The admission number is never stored here: sign-in resolves it against the
 * live `admission.admission_no`, and everything below refers to the admission
 * only by `admission.id`.
 */

/**
 * Where a cadet login's current password came from, recorded explicitly.
 * - `issued`: generated by school staff (at admission creation or a reset).
 * - `student_set`: chosen by the student (not possible yet; later PR).
 */
export const cadetPasswordSourceEnum = pgEnum("cadet_password_source", [
  "issued",
  "student_set",
]);

/**
 * One Cadet Portal login per admission. `email` is a placeholder Better Auth
 * requires (`<admissionId>@cadet.campuspilot.invalid`); it is never used to
 * sign in because email sign-in is disabled on the cadet instance. `name` is
 * left empty on purpose: the student's name belongs to the admission and is
 * never copied here, so it cannot go stale.
 */
export const cadetUser = pgTable("cadet_user", {
  id: text("id").primaryKey(),
  name: text("name").notNull().default(""),
  email: text("email").notNull().unique(),
  emailVerified: boolean("email_verified").default(false).notNull(),
  image: text("image"),
  createdAt: timestamp("created_at").defaultNow().notNull(),
  updatedAt: timestamp("updated_at")
    .defaultNow()
    .$onUpdate(() => /* @__PURE__ */ new Date())
    .notNull(),
  /** The admission this login belongs to; one login per admission. */
  admissionId: text("admission_id")
    .notNull()
    .unique()
    .references(() => admissionTable.id, { onDelete: "cascade" }),
  passwordSource: cadetPasswordSourceEnum("password_source").notNull(),
  /** When staff last issued a password for this login. */
  issuedAt: timestamp("issued_at", { withTimezone: true }).notNull(),
  /**
   * Staff user who last issued the password. Null once that staff account is
   * deleted; the issue time stays.
   */
  issuedBy: text("issued_by").references(() => user.id, {
    onDelete: "set null",
  }),
});

